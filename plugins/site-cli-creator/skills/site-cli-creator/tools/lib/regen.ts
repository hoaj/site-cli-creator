import { existsSync, readdirSync } from "node:fs";
import { basename, join } from "node:path";
import { fail } from "./output";

const COMMANDS_START = "<!-- commands:start -->";
const COMMANDS_END = "<!-- commands:end -->";

/** The modules regen imports: *.ts in a folder, tests and declarations left out, sorted by file name. */
export function moduleFiles(dir: string): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith(".ts") && !f.endsWith(".test.ts") && !f.endsWith(".d.ts"))
    .sort();
}

/** The file a command belongs in: its name with dashes (`subscription show` → `subscription-show.ts`). */
export function commandFileName(name: string): string {
  return `${name.trim().split(/\s+/).join("-")}.ts`;
}

/** Whether a module's default export is a command (runtime/command.ts): a name, the Operations it uses, a run function. */
export function isCommandExport(value: unknown): boolean {
  if (typeof value !== "object" || value === null) return false;
  const c = value as Record<string, unknown>;
  return typeof c.name === "string" && Array.isArray(c.uses) && typeof c.run === "function";
}

export const SHARED_CODE_HOME = "Shared code for commands goes in cli/src/lib/.";

function camel(name: string): string {
  const words = name.split(/[^A-Za-z0-9]+/).filter(Boolean);
  const id = words.map((w, i) => (i === 0 ? w[0]!.toLowerCase() + w.slice(1) : w[0]!.toUpperCase() + w.slice(1))).join("");
  return /^[A-Za-z_$]/.test(id) ? id : `_${id}`;
}

// Names an import binding may not take (an Operation file can be called delete.ts).
const RESERVED = new Set(
  ("break case catch class const continue debugger default delete do else enum export extends false finally for " +
    "function if import in instanceof new null return super switch this throw true try typeof var void while with " +
    "yield let static implements interface package private protected public await arguments eval").split(" "),
);

/** registry.ts: static imports, so `bun build --compile` bundles every Operation and command. */
export function registrySource(operationFiles: string[], commandFiles: string[]): string {
  const used = new Set<string>();
  const binding = (wanted: string) => {
    const base = RESERVED.has(wanted) ? `${wanted}Op` : wanted;
    let id = base;
    for (let i = 2; used.has(id); i++) id = `${base}${i}`;
    used.add(id);
    return id;
  };
  const ops = operationFiles.map((f) => ({ id: binding(camel(basename(f, ".ts"))), path: `./operations/${basename(f, ".ts")}` }));
  const cmds = commandFiles.map((f) => ({ id: binding(`${camel(basename(f, ".ts"))}Command`), path: `./commands/${basename(f, ".ts")}` }));
  const lines = [
    "// GENERATED by site-cli-creator's regen.ts from src/operations/ and src/commands/.",
    "// Rerun regen after adding or renaming a file there; edits here are overwritten.",
    ...ops.map((o) => `import ${o.id} from "${o.path}";`),
    ...cmds.map((c) => `import ${c.id} from "${c.path}";`),
    "",
    `export const operations = [${ops.map((o) => o.id).join(", ")}];`,
    `export const commands = [${cmds.map((c) => c.id).join(", ")}];`,
    "",
  ];
  return lines.join("\n");
}

export function setNeedsChrome(siteSource: string, needsChrome: boolean): string {
  const pattern = /(\bneedsChrome:\s*)(true|false)\b/;
  if (!pattern.test(siteSource)) fail("site.ts has no `needsChrome: true|false` field");
  return siteSource.replace(pattern, `$1${needsChrome}`);
}

type HelpFlag = {
  name: string;
  boolean: boolean;
  required: boolean;
  multiple: boolean;
  /** Placeholder for the value: the enum values, "n" for numbers, else the flag name. */
  value: string;
  description?: string;
};
type HelpCommand = { name: string; summary: string; flags: HelpFlag[]; write: boolean };

function normalizeFlag(raw: unknown, key?: string): HelpFlag | null {
  if (typeof raw !== "object" || raw === null) return null;
  const f = raw as Record<string, unknown>;
  const name = String(f.name ?? key ?? "").replace(/^-+/, "");
  if (!name) return null;
  const values = Array.isArray(f.values) ? f.values.map(String) : [];
  return {
    name,
    boolean: f.type === "boolean",
    required: f.required === true,
    multiple: f.multiple === true,
    value: values.length ? values.join("|") : f.type === "number" ? "n" : name,
    ...(typeof f.description === "string" && f.description ? { description: f.description } : {}),
  };
}

function flagsOf(raw: unknown): HelpFlag[] {
  if (Array.isArray(raw)) return raw.map((f) => normalizeFlag(f)).filter((f): f is HelpFlag => f !== null);
  if (typeof raw === "object" && raw !== null) {
    return Object.entries(raw).map(([k, v]) => normalizeFlag(v, k)).filter((f): f is HelpFlag => f !== null);
  }
  return [];
}

/** Task commands from `<cli> help` JSON (runtime/help.ts). Flags may be a list or a map. */
export function helpCommands(help: unknown): HelpCommand[] {
  const list = (help as { commands?: unknown })?.commands;
  if (!Array.isArray(list)) fail("`help` printed no commands array");
  return list
    .filter((c): c is Record<string, unknown> => typeof c === "object" && c !== null && typeof c.name === "string")
    .map((c) => ({
      name: c.name as string,
      summary: typeof c.summary === "string" ? c.summary : "",
      flags: flagsOf(c.flags),
      write: c.write === true,
    }));
}

function cell(text: string): string {
  return text.replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");
}

function flagUsage(f: HelpFlag): string {
  const usage = f.boolean ? `--${f.name}` : `--${f.name} <${f.value}>`;
  return `${f.required ? usage : `[${usage}]`}${f.multiple ? "..." : ""}`;
}

/** The `## Commands` table: one row per Task command, writes marked. */
export function commandsTable(skill: string, commands: HelpCommand[]): string {
  const rows = ["| Command | Flags | Does |", "|---|---|---|"];
  if (commands.length === 0) rows.push("| (none yet) | | |");
  for (const c of commands) {
    const flags = c.flags.map((f) => {
      const usage = `\`${cell(flagUsage(f))}\``;
      return f.description ? `${usage} ${cell(f.description)}` : usage;
    });
    const summary = cell(c.summary.trim());
    const sentence = summary && !/[.!?]$/.test(summary) ? `${summary}.` : summary;
    const does = c.write ? `**Write.** ${sentence} Dry run unless \`--confirm\`.` : summary;
    rows.push(`| \`${skill} ${c.name}\` | ${flags.join("<br>")} | ${does.trim()} |`);
  }
  return rows.join("\n");
}

export function replaceCommandsBlock(skillMd: string, table: string): string {
  const start = skillMd.indexOf(COMMANDS_START);
  const end = skillMd.indexOf(COMMANDS_END);
  if (start === -1 || end === -1 || end < start) {
    fail(`SKILL.md needs ${COMMANDS_START} and ${COMMANDS_END} around the command table`);
  }
  return `${skillMd.slice(0, start + COMMANDS_START.length)}\n${table}\n${skillMd.slice(end)}`;
}

export function cliPaths(skillDir: string) {
  const cli = join(skillDir, "cli");
  return {
    cli,
    operations: join(cli, "src", "operations"),
    commands: join(cli, "src", "commands"),
    registry: join(cli, "src", "registry.ts"),
    site: join(cli, "src", "site.ts"),
    main: join(cli, "src", "main.ts"),
    skillMd: join(skillDir, "SKILL.md"),
  };
}
