describe.skipIf(!realStarterReady)("against the real Starter code and the fixture's expected code", () => {
  for (const auth of ["login", "none"] as const) {
    test(`auth ${auth}`, async () => {
      const plugin = join(work, `real-${auth}`);
      const env = { ...process.env, STARTER_DIR: REAL_STARTER };
      const spawn = (args: string[]) => {
        const p = Bun.spawnSync([process.execPath, ...args], { env, stdout: "pipe", stderr: "pipe" });
        expect(p.exitCode, p.stdout.toString() + p.stderr.toString()).toBe(0);
      };
      spawn([NEW, "--dir", plugin, "--plugin", "shop", "--repo", "acme/shop", "--description", "d", "--maintainer", "octo", "--no-labels", "--skip-checks"]);
      spawn([ADD_SKILL, "--dir", plugin, "--skill", "shop", "--origin", "http://127.0.0.1:9", "--auth", auth]);
      const skill = join(plugin, "skills", "shop");
      symlinkSync(join(GENERATOR_ROOT, "node_modules"), join(skill, "cli", "node_modules"));
      const { copyExpected } = await import(EXPECTED);
      copyExpected(auth, join(skill, "cli", "src"), {
        plugin: "shop",
        skill: "shop",
        repo: "acme/shop",
        generatorVersion: generatorVersion(),
        origin: "http://127.0.0.1:9",
      });
      const site = join(skill, "cli/src/site.ts");
      writeFileSync(site, readFileSync(site, "utf8").replace(/needsChrome: true/, "needsChrome: false"));

      const r = regen(skill);
      expect(r.code, r.stderr).toBe(0);
      expect(r.out.needsChrome).toBe(true); // addNote is a write
      const names = r.out.commands.map((c: { name: string }) => c.name);
      expect(names).toEqual(["invoice list", "invoice show", "note add", "subscription show"]);
      expect(r.out.commands.find((c: { name: string }) => c.name === "note add").write).toBe(true);
      const md = readFileSync(join(skill, "SKILL.md"), "utf8");
      expect(md).toMatch(/\| `shop note add` \| `--text <text>`[^|]*\| \*\*Write\.\*\*/);
      expect(md).toContain("`shop invoice list`");
      expect(readFileSync(site, "utf8")).toContain("needsChrome: true");
    });
  }
});
